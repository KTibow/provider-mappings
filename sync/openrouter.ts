/**
 * OpenRouter sync -> hosts/<host>/openrouter.toml.
 *
 * Unauthenticated public data only:
 *   GET /api/v1/models?output_modalities=all          catalog (documented)
 *   GET /api/frontend/v1/rankings/models?view=month   trailing-month volume (undocumented)
 *   GET /api/frontend/v1/stats/endpoint?permaslug=…   one row per upstream (undocumented)
 *
 * stats/endpoint is called every hour for models at or above MIN_MONTHLY_USD
 * estimated spend and models added in the last NEW_MODEL_DAYS; every other model
 * once a day (rows of models not fetched in a run are kept). Requests are sequential at
 * about 1/s. If a call fails or changes shape, that model's previous rows are
 * kept and the run exits non-zero; rows are only removed when OpenRouter
 * answers and no longer lists them.
 */
import fs from 'node:fs'
import path from 'node:path'
import { Registry, baseModels, fetchOrModels, normalizedForms, settlePin, shortName, tierMismatch, toCatalog, type Catalog, type OrModel } from '../lib/models.ts'
import { loadAliases, parseBaseUrl, resolveHost } from '../lib/host.ts'
import { SDK_DEFAULT_BASE, fillHostVariables } from '../lib/sdk-hosts.ts'
import { probeHour } from '../lib/discover.ts'
import { getJson } from '../lib/http.ts'
import { HOSTS_DIR, STATE_DIR, hostFile } from '../lib/paths.ts'
import { byKey, cleanQuant, emptyRows, formatRows, guessPin, readRowsFile, stableJson, writeIfChanged, type ReviewRow, type Row, type RowsFile } from '../lib/rows.ts'
import { readState, writeReport, writeState, type Conflict, type Drop } from '../lib/state.ts'

const OR = 'https://openrouter.ai'
const RANKINGS_URL = `${OR}/api/frontend/v1/rankings/models?view=month`
const MIN_MONTHLY_USD = 100
/** New models have no trailing volume yet; fetch them anyway so sellers can list them on day one. */
const NEW_MODEL_DAYS = 30
/** How long rows of a model OpenRouter delisted stay published without a refresh. */
const DELISTED_KEEP_DAYS = 30
/** Refuse to write a run that drops more than this share of live rows. */
const MAX_DROP_SHARE = 0.1
/** Debug aid: only call stats/endpoint for the first N selected models; the rest keep their rows. */
const LIMIT = process.env.OR_LIMIT ? Number(process.env.OR_LIMIT) : Infinity
const REQ = { minIntervalMs: 1100, attempts: 5 }
const CATALOG_FILE = path.join(STATE_DIR, 'catalog.json')

const HEADER = [
  'Generated by sync/openrouter.ts from OpenRouter\'s public endpoint stats.',
  'Do not edit: this file is rewritten every hour. Put fixes and additions in',
  'manual.toml next to it, which takes precedence.',
]

// ---------------------------------------------------------------- shapes

interface RankingRow {
  model_permaslug: string
  variant: string
  total_prompt_tokens: number
  total_completion_tokens: number
  total_native_tokens_cached?: number
  count?: number
  image_output_requests?: number
}

interface Endpoint {
  provider_slug: string
  provider_permaslug?: string
  provider_model_id: string
  provider_info: { baseUrl: string | null }
  quantization?: string | null
  is_disabled?: boolean
  is_hidden?: boolean
}

async function fetchRankings(): Promise<RankingRow[]> {
  const res = await getJson<{ data?: unknown }>(RANKINGS_URL, { ...REQ, cacheTtlMs: 30 * 60_000 })
  const data = res.data
  if (!Array.isArray(data) || data.length < 50) throw new Error(`rankings: expected { data: [...] } with many rows, got ${JSON.stringify(res).slice(0, 200)}`)
  for (const r of data as RankingRow[])
    if (typeof r?.model_permaslug !== 'string' || typeof r.total_prompt_tokens !== 'number' || typeof r.total_completion_tokens !== 'number')
      throw new Error(`rankings: unexpected row shape ${JSON.stringify(r).slice(0, 200)}`)
  return data as RankingRow[]
}

async function fetchEndpoints(permaslug: string): Promise<Endpoint[]> {
  const url = `${OR}/api/frontend/v1/stats/endpoint?permaslug=${encodeURIComponent(permaslug)}&variant=standard`
  const res = await getJson<{ data?: unknown }>(url, { ...REQ, cacheTtlMs: 30 * 60_000 })
  if (!Array.isArray(res.data)) throw new Error(`stats/endpoint ${permaslug}: expected { data: [...] }, got ${JSON.stringify(res).slice(0, 200)}`)
  for (const e of res.data as Endpoint[])
    if (typeof e?.provider_model_id !== 'string' || typeof e.provider_slug !== 'string' || typeof e.provider_info !== 'object' || e.provider_info === null || !('baseUrl' in e.provider_info))
      throw new Error(`stats/endpoint ${permaslug}: unexpected endpoint shape ${JSON.stringify(e).slice(0, 300)}`)
  return res.data as Endpoint[]
}

/** Estimated monthly spend per permaslug: tokens × list price, all variants priced at the base model's price. */
function monthlySpend(rankings: RankingRow[], bySlug: Map<string, OrModel>): Map<string, number> {
  const spend = new Map<string, number>()
  for (const r of rankings) {
    const p = bySlug.get(r.model_permaslug)?.pricing
    if (!p) continue
    const n = (k: string) => {
      const v = Number(p[k] ?? 0)
      return Number.isFinite(v) && v > 0 ? v : 0
    }
    const cached = r.total_native_tokens_cached ?? 0
    const usd =
      Math.max(0, r.total_prompt_tokens - cached) * n('prompt') +
      cached * (n('input_cache_read') || n('prompt')) +
      r.total_completion_tokens * n('completion') +
      (r.count ?? 0) * n('request') +
      (r.image_output_requests ?? 0) * n('image')
    spend.set(r.model_permaslug, (spend.get(r.model_permaslug) ?? 0) + usd)
  }
  return spend
}

// ---------------------------------------------------------------- review rules


/**
 * Domains where the first label is the customer's own resource or account. OpenRouter's
 * endpoint there ("openrouter-us-resource.services.ai.azure.com") becomes the family
 * every customer's resource belongs to ("{resource}.services.ai.azure.com").
 */
const PER_ACCOUNT_DOMAINS: [RegExp, string][] = [
  [/^[^.]+\.(services\.ai\.azure\.com|openai\.azure\.com|cognitiveservices\.azure\.com)$/, '{resource}'],
  [/^[^.]+\.[a-z0-9-]+\.maas\.aliyuncs\.com$/, '{account}'],
]

/**
 * The host key for an endpoint, or why there is none. Hostnames made for
 * OpenRouter alone ("openrouter.inference.crusoecloud.com") are not hosts anyone
 * else can call, so they are skipped, not published.
 */
function endpointHost(provider: string, baseUrl: string): { host: string } | { skip: string } {
  // Providers OpenRouter calls through an SDK ("not_used"): the HTTP host a seller would use.
  const parsed = parseBaseUrl(baseUrl === 'not_used' || !baseUrl ? SDK_DEFAULT_BASE[provider] : fillHostVariables(baseUrl))
  if (parsed.kind === 'none') return { skip: parsed.reason }
  for (const [re, ph] of PER_ACCOUNT_DOMAINS) if (re.test(parsed.host)) return { host: `${ph}.${parsed.host.slice(parsed.host.indexOf('.') + 1)}` }
  if (/openrouter/i.test(parsed.host)) return { skip: 'hostname is OpenRouter-only' }
  return { host: parsed.host }
}

/** Why this endpoint should not be trusted without a person looking, or undefined. */
function reviewReason(e: Endpoint, baseUrl: string): string | undefined {
  const id = e.provider_model_id
  if (/openrouter/i.test(id)) return `model id is OpenRouter-only (${e.provider_slug})`
  // The hostname was handled by endpointHost; an OpenRouter-specific path is not callable elsewhere.
  const urlPath = baseUrl.replace(/^[a-z]+:\/\/[^/]*/i, '')
  if (/openrouter/i.test(urlPath) || /\/partner\/v\d|\/integrations\//i.test(urlPath)) return `base URL is OpenRouter-only (${baseUrl})`
  // Volcengine / BytePlus inference endpoints ("ep-20251223020539-6m7wz") belong to one account.
  if (/^ep-[a-z0-9]+-[a-z0-9]+$/i.test(id) && /\d{10}/.test(id)) return `model id is a per-account endpoint (${e.provider_slug})`
  if (e.is_disabled) return `endpoint disabled on OpenRouter (${e.provider_slug})`
  if (e.is_hidden) return `endpoint hidden on OpenRouter (${e.provider_slug})`
  return undefined
}

// ---------------------------------------------------------------- main

function readPrevious() {
  const prev = new Map<string, RowsFile>()
  if (fs.existsSync(HOSTS_DIR))
    for (const host of fs.readdirSync(HOSTS_DIR)) {
      const f = hostFile(host, 'openrouter')
      if (fs.existsSync(f)) prev.set(host, readRowsFile(f))
    }
  return prev
}

async function main() {
  const t0 = Date.now()
  const aliases = loadAliases()
  const failures: string[] = []

  const models = await fetchOrModels()
  const prevCatalog: Catalog = fs.existsSync(CATALOG_FILE) ? JSON.parse(fs.readFileSync(CATALOG_FILE, 'utf8')) : {}
  const newCatalog = toCatalog(models, prevCatalog)
  const reg = Registry.load(newCatalog)
  const catalog = baseModels(models)
  // Rankings only set the spend threshold. If they fail, carry on with the
  // models that already have rows plus new ones, and report the failure.
  let rankings: RankingRow[] = []
  try {
    rankings = await fetchRankings()
  } catch (e) {
    failures.push(`rankings: ${(e as Error).message}`)
    console.error(`  ! rankings unavailable, selecting only mapped and new models: ${(e as Error).message}`)
  }
  const bySlug = new Map(catalog.map((m) => [m.canonical_slug, m]))
  const spend = monthlySpend(rankings, bySlug)
  const canonOf = (m: OrModel) => reg.ofOpenRouter(m.id)

  const prev = readPrevious()
  // A row written before OpenRouter renamed its model ("formerly") is that model.
  const canon = (model: string) => reg.explicit(model) ?? model
  const prevCanon = new Set<string>()
  for (const f of prev.values()) for (const r of [...f.rows.values(), ...f.review.values()]) prevCanon.add(canon(r.model))

  // Delisted models keep their rows for DELISTED_KEEP_DAYS: OpenRouter going quiet
  // about a model is not the host dropping it, but nothing refreshes those rows any
  // more, so they expire (the host's own list and models.dev still cover live routes).
  const delistedSince = (model: string) => reg.catalog[canon(model)]?.delisted
  const delistedFresh = (model: string) => {
    const d = delistedSince(model)
    return !!d && Date.now() - Date.parse(d) < DELISTED_KEEP_DAYS * 86_400_000
  }

  // A catalog that suddenly lost many of our models is more likely broken than real.
  // Models it delisted on earlier runs are not news.
  const catalogCanon = new Set(catalog.map(canonOf))
  const vanished = [...prevCanon].filter((c) => !catalogCanon.has(c) && !delistedSince(c))
  if (prevCanon.size >= 20 && vanished.length > prevCanon.size * 0.2)
    throw new Error(`catalog lost ${vanished.length} of ${prevCanon.size} mapped models at once; refusing to drop them (${vanished.slice(0, 10).join(', ')}…)`)

  // The catalog stands on its own: new models reach models.json even if the rest of this run fails or stops early.
  writeIfChanged(CATALOG_FILE, stableJson(newCatalog, 1))

  const newSince = Date.now() / 1000 - NEW_MODEL_DAYS * 86_400
  // Busy and new models every hour; every other model once a day, in an hour
  // picked by its name (rows of models not fetched this run are kept).
  const hour = new Date().getUTCHours()
  const selected = catalog
    .filter((m) => (spend.get(m.canonical_slug) ?? 0) >= MIN_MONTHLY_USD || (m.created ?? 0) >= newSince || probeHour(m.canonical_slug) === hour || (process.env.OPENROUTER_ALL === '1'))
    .sort((a, b) => (spend.get(b.canonical_slug) ?? 0) - (spend.get(a.canonical_slug) ?? 0) || byKey(a.canonical_slug, b.canonical_slug))
  console.log(`openrouter: ${catalog.length} models, ${selected.length} selected (>= $${MIN_MONTHLY_USD}/month, added in the last ${NEW_MODEL_DAYS} days, or due for their daily refresh)`)

  const next = new Map<string, RowsFile>()
  /** provider -> why its endpoints have no host anyone else can call. */
  const skipped = new Map<string, string>()
  const conflicts = new Map<string, Conflict>()
  const fetched = new Set<string>()
  /** Every (host, native id) claim, resolved after all models are fetched so order (spend) never decides. */
  interface Claim { model: string; slug: string; row: Row; reason?: string }
  const claims = new Map<string, { host: string; id: string; list: Claim[] }>()
  let throttled = 0
  const empty = readState('openrouter').empty ?? {}

  let i = 0
  for (const m of selected) {
    const model = canonOf(m)
    if (i++ >= LIMIT) continue
    if (throttled >= 5) continue // being rate-limited: keep previous rows for the rest
    let eps: Endpoint[]
    try {
      eps = await fetchEndpoints(m.canonical_slug)
      throttled = 0
    } catch (e) {
      const msg = (e as Error).message
      if (/HTTP (429|403)/.test(msg)) throttled++
      failures.push(`${m.canonical_slug}: ${msg}`)
      console.error(`  ! ${m.canonical_slug}: ${msg}`)
      if (throttled >= 5) console.error('  ! rate-limited 5 times in a row; stopping, previous rows kept for the remaining models')
      continue
    }
    if (eps.length === 0 && prevCanon.has(model)) {
      // A listed model with no endpoints at all looks like an outage, not a removal,
      // until it has lasted DELISTED_KEEP_DAYS.
      const since = (empty[model] ??= new Date().toISOString().slice(0, 10))
      if (Date.now() - Date.parse(since) < DELISTED_KEEP_DAYS * 86_400_000) {
        failures.push(`${m.canonical_slug}: stats/endpoint returned no endpoints since ${since}; kept previous rows`)
        continue
      }
    } else delete empty[model]
    fetched.add(model)
    if (i % 25 === 0) console.log(`  ${i}/${Math.min(selected.length, LIMIT)} ${m.canonical_slug}`)

    for (const e of eps) {
      const nativeId = e.provider_model_id.trim()
      if (!nativeId) continue
      const baseUrl = String(e.provider_info.baseUrl ?? '')
      const quant = cleanQuant(e.quantization)
      // A moving native id ("…-latest") never goes live under a pinned model id.
      const settled = settlePin(reg, nativeId, model, guessPin(nativeId))
      const row: Row = { ...(settled ?? { model, pin: 'floating' as const }), ...(quant ? { quant } : {}) }
      const movingReason = settled ? undefined : `native id is a moving alias; floating rows only go under "~" model ids`
      const provider = e.provider_slug.split('/')[0]!
      const where = endpointHost(provider, baseUrl)
      if ('skip' in where) {
        skipped.set(provider, `${where.skip} (${baseUrl || 'no base URL'})`)
        continue
      }
      const host = resolveHost(aliases, where.host)
      // The same rule the other syncs follow: OpenRouter files some tiers under the
      // base model ("kimi-k2.7-code-highspeed"); those wait for a person.
      // ...unless model-aliases.toml names the id explicitly (Tencent's "hy-mt2-lite" is its 1.8B).
      const tier = reg.explicit(nativeId) === row.model ? undefined : tierMismatch(nativeId, row.model)
      const tierReason = tier ? `native id has "${tier}", which ${row.model} lacks: a tier or variant, not the model itself` : undefined
      const reason = reviewReason(e, baseUrl) ?? movingReason ?? tierReason
      const k = `${host}\0${nativeId}`
      if (!claims.has(k)) claims.set(k, { host, id: nativeId, list: [] })
      claims.get(k)!.list.push({ model: row.model, slug: m.canonical_slug, row, reason })
    }
  }

  // Resolve claims. One model: live if any of its endpoints is clean (quant kept
  // only if all agree). Several models: only one whose own name is the native id
  // goes live; otherwise none does, and the claim is a conflict for a person.
  const nativeForms = (id: string) => new Set(normalizedForms(id.slice(id.lastIndexOf('/') + 1)))
  for (const [k, { host, id, list }] of [...claims].sort(([a], [b]) => byKey(a, b))) {
    if (!next.has(host)) next.set(host, emptyRows())
    const file = next.get(host)!
    const models = [...new Set(list.map((c) => c.model))].sort(byKey)
    let winner: string | undefined = models.length === 1 ? models[0] : undefined
    if (models.length > 1) {
      const forms = nativeForms(id)
      const named = models.filter((mid) => normalizedForms(shortName(mid)).some((f) => forms.has(f)))
      if (named.length === 1) winner = named[0]
      conflicts.set(k, {
        host, id,
        chosen: winner ? { source: 'openrouter', model: winner, note: 'its name matches the native id' } : { source: 'openrouter', model: '(none published)', note: 'several OpenRouter models list this id' },
        others: models.filter((x) => x !== winner).map((x) => ({ source: 'openrouter', model: x, note: list.find((c) => c.model === x)!.slug })),
      })
    }
    if (!winner) {
      const c = list[0]!
      file.review.set(id, { ...c.row, reason: `several OpenRouter models list this id (${models.join(', ')})` })
      continue
    }
    const mine = list.filter((c) => c.model === winner)
    const clean = mine.filter((c) => !c.reason)
    if (!clean.length) {
      file.review.set(id, { ...mine[0]!.row, reason: mine[0]!.reason! })
      continue
    }
    const quants = new Set(clean.map((c) => c.row.quant))
    const row: Row = { ...clean[0]!.row }
    if (quants.size !== 1) delete row.quant
    file.rows.set(id, row)
  }

  // Keep the last good rows of every previously mapped model we did not (successfully)
  // fetch, and of delisted models while they are fresh (see delistedFresh).
  const keep = (model: string) => !fetched.has(canon(model)) && (catalogCanon.has(canon(model)) || delistedFresh(model))
  for (const [host, f] of prev) {
    for (const [id, r] of f.rows) {
      if (!keep(r.model)) continue
      if (!next.has(host)) next.set(host, emptyRows())
      const n = next.get(host)!
      if (!n.rows.has(id)) n.rows.set(id, r)
    }
    for (const [id, r] of f.review) {
      if (!keep(r.model)) continue
      if (!next.has(host)) next.set(host, emptyRows())
      const n = next.get(host)!
      if (!n.rows.has(id) && !n.review.has(id)) n.review.set(id, r)
    }
  }

  // Record every live row we are removing, and why.
  const drops: Drop[] = []
  for (const [host, f] of prev)
    for (const [id, r] of f.rows) {
      if (next.get(host)?.rows.has(id)) continue
      const rv = next.get(host)?.review.get(id)
      drops.push({
        host, id,
        reason: rv
          ? `moved to needs-review: ${rv.reason}`
          : delistedSince(r.model) ? `${r.model} was delisted on ${delistedSince(r.model)}; its rows expired after ${DELISTED_KEEP_DAYS} days`
          : !catalogCanon.has(canon(r.model)) ? `${r.model} is no longer in the OpenRouter catalog`
          : `OpenRouter no longer lists this endpoint for ${r.model}`,
      })
    }

  // A run that would remove a large share of published rows is more likely a
  // shape change upstream than real removals: write nothing.
  // Expiring delisted rows is planned, not a shape change, so it doesn't count.
  const prevLive = [...prev.values()].reduce((n, f) => n + f.rows.size, 0)
  const surprising = drops.filter((d) => !d.reason.includes('its rows expired'))
  if (prevLive >= 100 && surprising.length > prevLive * MAX_DROP_SHARE)
    throw new Error(`would drop ${surprising.length} of ${prevLive} live rows at once (limit ${MAX_DROP_SHARE * 100}%); refusing. First few: ${surprising.slice(0, 5).map((d) => `${d.host} ${d.id}: ${d.reason}`).join('; ')}`)

  // Write.
  const hosts = new Set([...prev.keys(), ...next.keys()])
  let changed = 0
  for (const host of [...hosts].sort(byKey)) {
    const f = next.get(host)
    const text = f && (f.rows.size || f.review.size) ? formatRows(HEADER, f) : null
    if (writeIfChanged(hostFile(host, 'openrouter'), text)) changed++
  }
  if (skipped.size) console.log(`  skipped (no host anyone else can call): ${[...skipped].sort(([a], [b]) => byKey(a, b)).map(([p, why]) => `${p}: ${why}`).join('; ')}`)
  // Conflicts among models we did not fetch this run still stand, while their rows do.
  for (const c of readState('openrouter').conflicts) {
    const k = `${c.host}\0${c.id}`
    if (!conflicts.has(k) && ![c.chosen, ...c.others].some((x) => fetched.has(canon(x.model))) && keep(c.chosen.model)) conflicts.set(k, c)
  }
  for (const model of Object.keys(empty)) if (!catalogCanon.has(model)) delete empty[model]
  writeState('openrouter', { unmapped: {}, conflicts: [...conflicts.values()], empty })

  const live = [...next.values()].reduce((n, f) => n + f.rows.size, 0)
  const review = [...next.values()].reduce((n, f) => n + [...f.review.keys()].filter((k) => !f.rows.has(k)).length, 0)
  const stats = { skippedProviders: skipped.size, hosts: [...next.values()].filter((f) => f.rows.size).length, rows: live, review, conflicts: conflicts.size, selected: selected.length, fetched: fetched.size, failures: failures.length, drops: drops.length, filesChanged: changed }
  writeReport({ source: 'openrouter', finishedAt: new Date().toISOString(), ok: failures.length === 0, failures, drops, stats })
  console.log(`openrouter: ${JSON.stringify(stats)} in ${Math.round((Date.now() - t0) / 1000)}s`)
  // A few models failing is routine (their rows were kept); fail the run when
  // rankings broke, we got rate-limited, or failures are more than incidental.
  const modelFailures = failures.filter((f) => !f.startsWith('rankings:')).length
  const serious = failures.some((f) => f.startsWith('rankings:')) || throttled >= 5 || modelFailures > Math.max(3, selected.length * 0.02)
  if (failures.length) console.error(`openrouter: ${failures.length} failure(s); previous rows kept for the affected models.`)
  if (serious) process.exitCode = 1
}

await main().catch((e) => {
  console.error(`openrouter: FAILED, nothing written: ${(e as Error).stack ?? e}`)
  writeReport({ source: 'openrouter', finishedAt: new Date().toISOString(), ok: false, failures: [String((e as Error).message)], drops: [], stats: {} })
  process.exitCode = 1
})
