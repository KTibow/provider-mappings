/**
 * models.dev sync -> hosts/<host>/modelsdev.toml (lowest precedence).
 *
 * Fetches https://models.dev/api.json (no npm dependency) and records its
 * sha256 in upstream.lock. Every provider (or model-level override) with an
 * HTTP base URL becomes a host; the model's key is the native id. The
 * canonical comes from the model's declared `canonical_model_id`, then
 * model-aliases.toml / exact / normalized matching. Anything else is reported
 * as unmapped in state/modelsdev.json.
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import { parse } from 'smol-toml'
import { loadRegistry, registryMatcher, settlePin, splitVariant, tierMismatch, withOperation } from '../lib/models.ts'
import { loadAliases, parseBaseUrl, resolveHost } from '../lib/host.ts'
import { NO_HOST, SDK_DEFAULT_BASE, fillHostVariables } from '../lib/sdk-hosts.ts'
import { getText } from '../lib/http.ts'
import { HOSTS_DIR, LOCK_FILE, hostFile } from '../lib/paths.ts'
import { byKey, emptyRows, formatRows, guessPin, readRowsFile, tomlString, writeIfChanged, type Row, type RowsFile } from '../lib/rows.ts'
import { writeReport, writeState, type Conflict, type Drop } from '../lib/state.ts'
import { addRowEvidence, loadHostFiles } from '../lib/store.ts'

/** A run that would remove more than this share of rows writes nothing. */
const MAX_DROP_SHARE = 0.25
const URL_ = 'https://models.dev/api.json'

/** True when the URL's path contains the model's own name, i.e. the endpoint is for that one model. */
function perModelPath(api: string, key: string): boolean {
  const norm = (x: string) => x.toLowerCase().replace(/[^a-z0-9]/g, '')
  const name = norm(key.slice(key.lastIndexOf('/') + 1))
  return name.length >= 6 && norm(api.replace(/^[a-z]+:\/\/[^/]*/i, '')).includes(name)
}

interface MdModel {
  id: string
  canonical_model_id?: string
  provider?: { api?: string }
}
interface MdProvider {
  id: string
  api?: string | null
  models: Record<string, MdModel>
}

const HEADER = [
  'Generated by sync/modelsdev.ts from https://models.dev/api.json (MIT),',
  'snapshot pinned in upstream.lock. Lowest precedence. Do not edit: put fixes',
  'and additions in manual.toml next to it.',
]

function readLock(): Record<string, Record<string, string>> {
  return fs.existsSync(LOCK_FILE) ? (parse(fs.readFileSync(LOCK_FILE, 'utf8')) as Record<string, Record<string, string>>) : {}
}

function writeLock(lock: Record<string, Record<string, string>>) {
  const out = ['# Upstream snapshots the committed data was built from. Written by the syncs.']
  for (const name of Object.keys(lock).sort(byKey)) {
    out.push('', `[${name}]`)
    for (const k of Object.keys(lock[name]!).sort(byKey)) out.push(`${k} = ${tomlString(lock[name]![k]!)}`)
  }
  writeIfChanged(LOCK_FILE, out.join('\n') + '\n')
}

async function main() {
  const { text, fetchedAt } = await getText(URL_, { cacheTtlMs: 30 * 60_000, attempts: 4 })
  const sha256 = crypto.createHash('sha256').update(text).digest('hex')
  const api = JSON.parse(text) as Record<string, MdProvider> | null
  // One odd provider is skipped, not fatal; a file with few usable providers is a broken upstream.
  const providers = Object.entries(api && typeof api === 'object' ? api : {}).filter(([, p]) => !!p && typeof p.models === 'object' && p.models !== null)
  if (providers.length < 50) throw new Error(`api.json: unexpected shape (${providers.length} usable providers)`)

  const aliases = loadAliases()
  const { reg } = await loadRegistry()
  const matcher = registryMatcher(reg)
  addRowEvidence(matcher, loadHostFiles().files)

  const prev = new Map<string, RowsFile>()
  if (fs.existsSync(HOSTS_DIR))
    for (const h of fs.readdirSync(HOSTS_DIR)) if (fs.existsSync(hostFile(h, 'modelsdev'))) prev.set(h, readRowsFile(hostFile(h, 'modelsdev')))

  const next = new Map<string, RowsFile>()
  const unmapped: Record<string, string[]> = {}
  /** host\0id -> provider that wrote it and how, for intra-source conflicts. */
  const owner = new Map<string, { provider: string; declared: boolean }>()
  const conflicts = new Map<string, Conflict>()
  const skipped = new Map<string, string>()

  for (const [pid, p] of providers.sort(([a], [b]) => byKey(a, b))) {
    for (const [key, m] of Object.entries(p.models).sort(([a], [b]) => byKey(a, b))) {
      if (!m || typeof m !== 'object') continue
      // A per-model URL that names the model itself ("…/v1/genai/black-forest-labs/flux.1-dev")
      // selects it by path: there is no `model` string to send, so there is no row.
      if (m.provider?.api && perModelPath(m.provider.api, key)) {
        skipped.set(`${pid} (per-model URLs)`, `the URL path selects the model (${m.provider.api})`)
        continue
      }
      const base = m.provider?.api ?? p.api ?? SDK_DEFAULT_BASE[pid]
      if (!base) {
        if (!NO_HOST[pid]) skipped.set(pid, 'no base URL and not in lib/sdk-hosts.ts: look at it')
        continue
      }
      const parsed = parseBaseUrl(fillHostVariables(base))
      if (parsed.kind === 'none') {
        skipped.set(m.provider?.api ? `${pid} (some models)` : pid, NO_HOST[pid] ?? parsed.reason)
        continue
      }
      const host = resolveHost(aliases, parsed.host)
      const nativeId = key.trim()

      let model: string | undefined
      let declared = false
      if (typeof m.canonical_model_id === 'string' && m.canonical_model_id) {
        // The declared slug, as OpenRouter spells it: an exact name, a Hugging Face id
        // or normalized spelling ("anthropic/claude-opus-4-8" is OpenRouter's
        // "anthropic/claude-opus-4.8"), or the same slug without a release date
        // ("…claude-haiku-4-5-20251001" is "claude-haiku-4.5"). Only a slug that is
        // none of these is a model OpenRouter doesn't have, and becomes its own id.
        const cmi = m.canonical_model_id
        const undated = cmi.replace(/-(\d{8}|\d{4}-\d{2}-\d{2})$/, '')
        const hit = reg.resolve(cmi) ?? matcher.match([cmi])?.model ?? (undated !== cmi ? (reg.resolve(undated) ?? matcher.match([undated])?.model) : undefined)
        // A declared slug nothing knows becomes its own id, unless it names a moving
        // alias ("mistralai/codestral-latest"): that is only ever a "~" id.
        model = hit && !tierMismatch(cmi, hit) ? hit : guessPin(cmi) === 'floating' ? reg.floatingFor(cmi) : reg.ofSlug(cmi)
        declared = true
        // A tier ("-highspeed") declared as its base model: use the tier's own
        // model id if OpenRouter has exactly that (vendor of the declared id +
        // native id), otherwise leave it unmapped. Never override a declaration
        // on a looser match.
        if (model && tierMismatch(nativeId, model)) {
          const vendor = model.replace(/^~/, '').split('/')[0]
          model = reg.explicit(`${vendor}/${nativeId}`)
        }
      }
      // No reuse of models.dev's own earlier rows: it declares its mappings, and a
      // bad earlier row must not outlive the fix.
      model ??= reg.explicit(nativeId)
      if (!model) {
        const hit = matcher.match([nativeId])?.model
        if (hit && !tierMismatch(nativeId, hit)) model = hit
      }
      if (!model) {
        ;(unmapped[host] ??= []).push(nativeId)
        continue
      }

      // "x:free" / "x:web": models.dev files the variant under its model; it is that model's variant.
      const variant = reg.explicit(nativeId) ? undefined : splitVariant(nativeId)
      if (variant && !splitVariant(model)) model = `${model}:${variant[1]}`
      model = withOperation(nativeId, model)
      const settled = settlePin(reg, nativeId, model, guessPin(nativeId))
      if (!settled) {
        ;(unmapped[host] ??= []).push(nativeId) // a moving alias with no "~" model id to sit under
        continue
      }
      model = settled.model
      const row: Row = settled
      if (!next.has(host)) next.set(host, emptyRows())
      const f = next.get(host)!
      const k = `${host}\0${nativeId}`
      const existing = f.rows.get(nativeId)
      if (existing && existing.model !== model) {
        const own = owner.get(k)!
        const c = conflicts.get(k) ?? { host, id: nativeId, chosen: { source: 'modelsdev', model: existing.model, note: own.provider }, others: [] }
        if (declared && !own.declared) {
          c.others.push(c.chosen)
          c.chosen = { source: 'modelsdev', model, note: pid }
          f.rows.set(nativeId, row)
          owner.set(k, { provider: pid, declared })
        } else c.others.push({ source: 'modelsdev', model, note: pid })
        conflicts.set(k, c)
        continue
      }
      if (!existing) {
        f.rows.set(nativeId, row)
        owner.set(k, { provider: pid, declared })
      }
    }
  }
  // Ids mapped by one provider on a host are not unmapped just because another provider on the same host lacked a mapping.
  for (const [h, ids] of Object.entries(unmapped)) unmapped[h] = ids.filter((id) => !next.get(h)?.rows.has(id))

  const drops: Drop[] = []
  for (const [host, f] of prev) for (const id of f.rows.keys()) if (!next.get(host)?.rows.has(id)) drops.push({ host, id, reason: `models.dev ${sha256.slice(0, 12)} no longer lists it with a usable base URL` })
  // A file that would remove a large share of rows is more likely gutted upstream than real removals.
  const prevRows = [...prev.values()].reduce((n, f) => n + f.rows.size, 0)
  if (prevRows >= 100 && drops.length > prevRows * MAX_DROP_SHARE)
    throw new Error(`would drop ${drops.length} of ${prevRows} rows at once (limit ${MAX_DROP_SHARE * 100}%); refusing. First few: ${drops.slice(0, 5).map((d) => `${d.host} ${d.id}`).join(', ')}`)

  for (const host of [...new Set([...prev.keys(), ...next.keys()])].sort(byKey)) {
    const f = next.get(host)
    writeIfChanged(hostFile(host, 'modelsdev'), f && (f.rows.size || f.review.size) ? formatRows(HEADER, f) : null)
  }
  writeState('modelsdev', { unmapped, conflicts: [...conflicts.values()] })

  // Only move the lock when the content changed, so an unchanged upstream makes no commit.
  const lock = readLock()
  if (lock.modelsdev?.sha256 !== sha256) {
    lock.modelsdev = { url: URL_, sha256, fetched_at: fetchedAt.toISOString().replace(/\.\d+Z$/, 'Z') }
    writeLock(lock)
  }

  const stats = {
    hosts: next.size,
    rows: [...next.values()].reduce((n, f) => n + f.rows.size, 0),
    unmapped: Object.values(unmapped).reduce((n, l) => n + l.length, 0),
    conflicts: conflicts.size,
    providersSkipped: skipped.size,
    drops: drops.length,
  }
  writeReport({ source: 'modelsdev', finishedAt: new Date().toISOString(), ok: true, failures: [], drops, stats })
  console.log(`modelsdev: ${JSON.stringify(stats)} (api.json sha256 ${sha256.slice(0, 12)})`)
  for (const [pid, why] of skipped) console.log(`  skipped ${pid}: ${why}`)
}

await main().catch((e) => {
  console.error(`modelsdev: FAILED, nothing written: ${(e as Error).stack ?? e}`)
  writeReport({ source: 'modelsdev', finishedAt: new Date().toISOString(), ok: false, failures: [String((e as Error).message)], drops: [], stats: {} })
  process.exitCode = 1
})
